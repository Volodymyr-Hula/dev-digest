#!/usr/bin/env bash
# PreToolUse hook (matcher: Write|Edit|NotebookEdit) for the write-capable subagents.
# Usage in agent frontmatter:  .../agent-write-scope.sh <profile>   (implementer | test-writer | doc-writer)
# stdin: hook JSON, the target is .tool_input.file_path (.tool_input.notebook_path for NotebookEdit).
# Exit 0 = allow, exit 2 = block (reason on stderr).
#
# Common rules (all profiles): fail closed (no jq, bad JSON, no path, unknown profile); reject `..` and `.`
# segments, paths outside $CLAUDE_PROJECT_DIR, a symlink in any component, an existing non-regular file.
# Profiles:
#   implementer  anything in the project EXCEPT tests, e2e flows/specs, migrations, package manifests and
#                lockfiles, docs/, specs/, .claude/, INSIGHTS.md, CLAUDE.md, .env*, server/clones/,
#                node_modules/, .git/
#   test-writer  ONLY test files and test helpers, e2e flows, e2e/specs/{coverage,seed-fixtures}.md
#   doc-writer   ONLY *.md under docs/ (minus docs/agent-prompts/) and {server,client,reviewer-core,e2e}/docs/
set -uo pipefail

PROFILE="${1-}"

deny() { echo "agent-write-scope[${PROFILE:-?}]: blocked: $*" >&2; exit 2; }

case "$PROFILE" in
  implementer|test-writer|doc-writer) ;;
  *) deny "unknown or missing profile '${PROFILE}' (expected implementer, test-writer or doc-writer)" ;;
esac

command -v jq >/dev/null 2>&1 || deny "jq is required by this hook but was not found"

input="$(cat)"
path="$(jq -er '.tool_input.file_path // .tool_input.notebook_path // empty' <<<"$input" 2>/dev/null)" \
  || deny "could not read .tool_input.file_path / .tool_input.notebook_path"
[[ -z "$path" ]] && deny "empty file path"

proj_raw="${CLAUDE_PROJECT_DIR:-$PWD}"
proj="$(cd "$proj_raw" 2>/dev/null && pwd -P)" || deny "cannot resolve project dir '$proj_raw'"

# Squeeze duplicate slashes, then reject dot segments before any further processing.
path="$(sed -E 's#/+#/#g' <<<"$path")"
if [[ "$path" =~ (^|/)\.\.(/|$) ]]; then deny "'..' segments are not allowed"; fi

if [[ "$path" == /* ]]; then
  case "$path" in
    "$proj"/*) rel="${path#"$proj"/}" ;;
    "${proj_raw%/}"/*) rel="${path#"${proj_raw%/}"/}" ;;
    *) deny "path is outside the project directory" ;;
  esac
else
  rel="${path#./}"
fi
if [[ "$rel" =~ (^|/)\.(/|$) ]]; then deny "'.' segments are not allowed"; fi
[[ -z "$rel" || "$rel" == */ ]] && deny "'$rel' is not a file path"

# A git worktree under .claude/worktrees/<name>/ is a full checkout of the repo: re-root at it and apply the
# same profile rules to the path inside it. Only a real (non-symlinked) linked worktree qualifies, i.e. its
# `.git` is a regular file starting with `gitdir:`; anything else under .claude/ stays out of scope.
if [[ "$rel" =~ ^\.claude/worktrees/([A-Za-z0-9_][A-Za-z0-9_.-]*)/(.+)$ ]]; then
  wt=".claude/worktrees/${BASH_REMATCH[1]}"
  inner="${BASH_REMATCH[2]}"
  for c in .claude .claude/worktrees "$wt" "$wt/.git"; do
    [[ -L "$proj/$c" ]] && deny "'$c' is a symlink"
  done
  [[ -f "$proj/$wt/.git" ]] && head -c 7 "$proj/$wt/.git" | grep -qx 'gitdir:' \
    || deny "'$wt' is not a git worktree"
  proj="$proj/$wt"
  rel="$inner"
fi

# ---- profile rules (regexes on the repo-relative path) ------------------------
PKG='(server|client|reviewer-core|e2e)'

implementer_denied() {
  local -a rules=(
    '(^|/)[^/]+\.test\.tsx?$'                                                  "test files are out of scope for this agent"
    '(^|/)__snapshots__/'                                                      "snapshots are test files"
    '^(server/test|reviewer-core/test|client/src/test|e2e/flows|e2e/specs)(/|$)' "test folders and e2e flows/specs are out of scope"
    '^server/src/db/migrations(/|$)'                                           "migrations are generated by 'pnpm db:generate', never written by hand"
    '(^|/)(package\.json|pnpm-lock\.yaml|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-workspace\.yaml)$' "dependencies change only through the package manager, which this agent may not run"
    "^($PKG/)?docs(/|\$)"                                                      "docs/ is out of scope"
    "^($PKG/)?specs(/|\$)"                                                     "specs/ is out of scope"
    '^\.(claude|cursor|git)(/|$)'                                              "agent config and .git are out of scope"
    '(^|/)(INSIGHTS|CLAUDE)\.md$'                                              "INSIGHTS.md and CLAUDE.md are out of scope"
    '(^|/)\.env[^/]*$'                                                         ".env files are out of scope"
    '^server/clones(/|$)'                                                      "server/clones/ is a gitignored clone, not project code"
    '(^|/)node_modules(/|$)'                                                   "node_modules/ is out of scope"
  )
  local i
  for ((i = 0; i < ${#rules[@]}; i += 2)); do
    if [[ "$rel" =~ ${rules[i]} ]]; then
      echo "${rules[i + 1]}"
      return 0
    fi
  done
  return 1
}

test_writer_allowed() {
  local name='[A-Za-z0-9_.-]+'
  [[ "$rel" =~ ^client/src/(.+/)?${name}\.test\.tsx?$ ]] && return 0
  [[ "$rel" =~ ^client/src/(.+/)?__snapshots__/${name}$ ]] && return 0
  [[ "$rel" =~ ^client/src/test/(.+/)?${name}\.(ts|tsx|json)$ ]] && return 0
  [[ "$rel" =~ ^(server|reviewer-core)/test/(.+/)?${name}\.(ts|tsx|json|snap|txt|md|diff|patch)$ ]] && return 0
  [[ "$rel" =~ ^e2e/flows/[0-9]{2}-[a-z0-9][a-z0-9-]*\.flow\.json$ ]] && return 0
  [[ "$rel" =~ ^e2e/specs/(coverage|seed-fixtures)\.md$ ]] && return 0
  return 1
}

doc_writer_allowed() {
  [[ "$rel" =~ ^docs/agent-prompts(/|$) ]] && return 1
  [[ "$rel" =~ ^($PKG/)?docs/(.+/)?[A-Za-z0-9][A-Za-z0-9_.-]*\.md$ ]] && return 0
  return 1
}

case "$PROFILE" in
  implementer)
    if reason="$(implementer_denied)"; then deny "'$rel': $reason"; fi
    ;;
  test-writer)
    test_writer_allowed || deny "'$rel' is not a test file location (client/src/**/*.test.ts(x), client/src/test/, server/test/, reviewer-core/test/, e2e/flows/NN-*.flow.json, e2e/specs/{coverage,seed-fixtures}.md)"
    ;;
  doc-writer)
    doc_writer_allowed || deny "'$rel' is not a docs location (*.md under docs/ except docs/agent-prompts/, or {server,client,reviewer-core,e2e}/docs/)"
    ;;
esac

# ---- filesystem checks ------------------------------------------------------
# Symlink check on every existing component, from the first segment down to the file.
walk=""
IFS='/' read -r -a parts <<<"$rel"
for part in "${parts[@]}"; do
  walk="${walk:+$walk/}$part"
  [[ -L "$proj/$walk" ]] && deny "'$walk' is a symlink"
done

full="$proj/$rel"
if [[ -e "$full" && ! -f "$full" ]]; then deny "'$rel' exists and is not a regular file"; fi
exit 0
